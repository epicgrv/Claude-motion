"""Writes remotion/src/videos/silver/vo.ts from the ElevenLabs voiceover: word times (faster-whisper transcript.json)
plus per-frame mouth opening (loudness 0..4) and viseme class (spectral centroid: 0 A, 1 E, 2 O) at 30 fps."""
import json, subprocess, numpy as np, os
import sys; D = os.path.dirname(os.path.abspath(__file__)); AUD = sys.argv[1] if len(sys.argv) > 1 else "vo_11labs.mp3"; OUT = sys.argv[2] if len(sys.argv) > 2 else "../../remotion/src/videos/silver/vo.ts"
src = os.path.join(D, AUD)
pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", src, "-ac", "1", "-ar", "16000", "-f", "s16le", "-"], capture_output=True).stdout
a = np.frombuffer(pcm, np.int16).astype(np.float32) / 32768
dur = len(a) / 16000
FPS, hop = 30, 16000 // 30
n = int(np.ceil(dur * FPS))
rms, cen = np.zeros(n), np.zeros(n)
for i in range(n):
    s = a[i * hop: i * hop + 1024]
    if len(s) < 64: continue
    rms[i] = np.sqrt(np.mean(s ** 2))
    sp = np.abs(np.fft.rfft(s * np.hanning(len(s)))); f = np.fft.rfftfreq(len(s), 1 / 16000)
    cen[i] = (sp * f).sum() / (sp.sum() + 1e-9)
db = 20 * np.log10(rms + 1e-6); ref = np.percentile(db[db > -50], 95) if (db > -50).any() else -20
m = np.clip((db - (ref - 30)) / 30, 0, 1)
m = np.convolve(m, [0.25, 0.5, 0.25], "same")
mouth = np.round(m * 4).astype(int)
voiced = cen[mouth >= 1]
lo, hi = np.percentile(voiced, 28), np.percentile(voiced, 78)
vis = np.where(cen < lo, 2, np.where(cen > hi, 1, 0)); vis[mouth == 0] = 0
T = json.load(open(os.path.join(D, "transcript.json")))
lines = []
for k, s in enumerate(T):
    ws = [{"w": w[0], "s": w[1], "e": w[2]} for w in s["words"]]
    who = "BUNKER" if s["text"].lower().startswith("a billion dollars") else "NAR"
    lines.append(f'  {{ id: "L{k+1:02d}", who: "{who}", s: {s["s"]:.2f}, e: {s["e"]:.2f}, words: {json.dumps(ws)} }},')
out = ["// generated by audio/silver-hunt/make_vo_ts.py from the ElevenLabs voiceover (word times s, mouth per 30 fps frame)",
       "export type Word = { w: string; s: number; e: number };",
       "export type Line = { id: string; who: string; s: number; e: number; words: Word[] };",
       f"export const VO_DUR = {dur:.2f};", "export const LINES: Line[] = [", *lines, "];",
       f'export const MOUTH = "{"".join(map(str, mouth))}";', f'export const VISEME = "{"".join(map(str, vis))}";']
open(os.path.join(D, OUT), "w").write("\n".join(out) + "\n")
print("dur", round(dur, 2), "frames", n, "visemes", np.bincount(vis[mouth > 0], minlength=3))
